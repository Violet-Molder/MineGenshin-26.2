package com.linweiyun.genshin.core.system.shield;

/**
 * 护盾的<b>作用范围</b>分类 —— 盾是「贴在本体上」还是「独立拿着一块」。
 */
public enum ShieldShape {

    /**
     * 罩型：有盾就生效，任何方向的攻击都会先打在盾上。
     *
     * <p>盾量信息显示在实体血条下方。
     */
    AURA,

    /**
     * 盾牌型：盾本身是一个独立存在（木盾丘丘人那种），只是被实体持有。
     *
     * <p>两个特点：
     * <ul>
     *   <li><b>有方向</b>：只抵挡打在盾面上的攻击，等价于免疫来自正面某个扇形的伤害；</li>
     *   <li><b>盾量不显示在血条上</b>，而是显示在手持的物品模型上，且<b>不跟随动画位移</b>
     *       —— 挥盾、下劈都不会让盾量标签跟着动。</li>
     * </ul>
     *
     * <p>目前只有「方向判定」这一半实装（{@link ShieldService} 里按
     * {@link ShieldState#heldYaw()} 算夹角），<b>手持模型上的盾量显示是占位</b>。
     */
    HELD
}
