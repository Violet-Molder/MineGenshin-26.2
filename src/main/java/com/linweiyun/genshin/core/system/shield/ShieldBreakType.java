package com.linweiyun.genshin.core.system.shield;

/**
 * 护盾的<b>击破方式</b>分类 —— 盾量是被什么扣掉的。
 *
 * <p>这一维和「伤害打不打得到本体」是两回事：元素盾照样能把伤害全挡下来，
 * 只是伤害不会扣它的盾量。
 */
public enum ShieldBreakType {

    /**
     * 元素盾：只能靠<b>元素附着</b>击破，伤害完全不起作用。
     *
     * <p>打九万伤害 2 单位风附着，和打一百伤害 2 单位风附着，效果一样。
     * 消耗按元素反应走（火盾用水打：1 单位水消耗 2 单位火）。
     */
    ELEMENT,

    /**
     * 伤害盾：打多少伤害扣多少盾量，元素附着不影响。
     */
    DAMAGE,

    /**
     * 混合盾：伤害与元素附着一起扣。
     */
    MIXED,

    /**
     * 白盾：全靠<b>韧性（削韧）</b>击破。
     *
     * <p>一般是怪物的盾。削韧值来自攻击信息（{@code ModDamageSpec#getPoiseDamage()}），
     * 不填时普通攻击默认 0.15、大剑默认 0.45。
     *
     * <p>⚠️ 独立的「韧性条 / 破韧硬直」系统还没做，这里只把削韧量接进盾量扣除。
     */
    POISE
}
